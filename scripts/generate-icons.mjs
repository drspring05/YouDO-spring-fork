// Builds every app icon from src/lib/appIconVariants.json:
// - Android: an adaptive icon per variant (vector foreground and background,
//   shared monochrome layer for themed icons) plus PNGs for Android 7.x.
// - Web: the default icon set in public/ and one folder per variant under
//   public/app-icons/<id>/ with its own manifest, so the web app installs with
//   the icon the person chose.
// Run with `npm run icons`.
import sharp from 'sharp';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const config = JSON.parse(readFileSync(join(root, 'src/lib/appIconVariants.json'), 'utf8'));
const { mark, variants } = config;
const publicDir = join(root, 'public');
const resDir = join(root, 'android/app/src/main/res');

const suffix = (v) => (v.id === config.default ? '' : `_${v.id}`);

// ── SVG (web + PNG source) ──────────────────────────────────────────────────
// `shape`: 'square' is full-bleed (maskable / iOS), 'rounded' an app tile,
// 'circle' the round launcher icon. The mark spans half the tile.
function iconSvg(v, size, shape) {
  const scale = (size * 0.5) / 16;
  const background =
    shape === 'circle'
      ? `<circle cx="${size / 2}" cy="${size / 2}" r="${size / 2}" fill="${v.background}"/>`
      : `<rect width="${size}" height="${size}" rx="${shape === 'rounded' ? size * 0.225 : 0}" fill="${v.background}"/>`;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${size} ${size}" width="${size}" height="${size}">
  ${background}
  <g fill="none" stroke-linecap="round" stroke-linejoin="round" stroke-width="${mark.stroke}" transform="translate(${size / 2} ${size / 2}) scale(${scale}) translate(-12 -12)">
    <path d="${mark.y}" stroke="${v.y}"/>
    <path d="${mark.tick}" stroke="${v.tick}"/>
  </g>
</svg>
`;
}

const png = (svg, size, file) => sharp(Buffer.from(svg)).resize(size, size).png().toFile(file);

// ── Android vectors ─────────────────────────────────────────────────────────
const toAndroidPath = (d) => d.replace(/(\d)\s+(\d)/g, '$1,$2');

function foregroundXml(v, monochrome = false) {
  const stroke = (color) => (monochrome ? '#FFFFFFFF' : `#FF${color.slice(1).toUpperCase()}`);
  const path = (d, color) => `        <path
            android:pathData="${toAndroidPath(d)}"
            android:fillColor="#00000000"
            android:strokeColor="${stroke(color)}"
            android:strokeWidth="${mark.stroke}"
            android:strokeLineCap="round"
            android:strokeLineJoin="round" />`;
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/generate-icons.mjs from src/lib/appIconVariants.json. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <group
        android:translateX="27"
        android:translateY="27"
        android:scaleX="2.25"
        android:scaleY="2.25">
${path(mark.y, v.y)}
${path(mark.tick, v.tick)}
    </group>
</vector>
`;
}

const backgroundXml = (v) => `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/generate-icons.mjs from src/lib/appIconVariants.json. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path
        android:fillColor="${v.background}"
        android:pathData="M0,0h108v108h-108z" />
</vector>
`;

const adaptiveXml = (v) => `<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_background${suffix(v)}"/>
    <foreground android:drawable="@drawable/ic_launcher_foreground${suffix(v)}"/>
    <monochrome android:drawable="@drawable/ic_launcher_monochrome"/>
</adaptive-icon>
`;

function manifestFor(v) {
  const base = `/app-icons/${v.id}`;
  return JSON.stringify(
    {
      name: 'YouDO',
      short_name: 'YouDO',
      description: 'Execution & Goal Tracker',
      theme_color: '#000000',
      background_color: '#000000',
      display: 'standalone',
      display_override: ['standalone', 'minimal-ui'],
      orientation: 'portrait',
      start_url: '/',
      scope: '/',
      id: 'youdo-app',
      icons: [
        { src: `${base}/icon-192.png`, sizes: '192x192', type: 'image/png', purpose: 'any' },
        { src: `${base}/icon-512.png`, sizes: '512x512', type: 'image/png', purpose: 'any' },
        { src: `${base}/icon-512-maskable.png`, sizes: '512x512', type: 'image/png', purpose: 'maskable' },
      ],
    },
    null,
    2,
  ) + '\n';
}

async function generate() {
  const densities = [
    ['mipmap-mdpi', 48],
    ['mipmap-hdpi', 72],
    ['mipmap-xhdpi', 96],
    ['mipmap-xxhdpi', 144],
    ['mipmap-xxxhdpi', 192],
  ];

  if (existsSync(resDir)) {
    writeFileSync(join(resDir, 'drawable/ic_launcher_monochrome.xml'), foregroundXml(variants[0], true));
    for (const v of variants) {
      writeFileSync(join(resDir, `drawable/ic_launcher_foreground${suffix(v)}.xml`), foregroundXml(v));
      writeFileSync(join(resDir, `drawable/ic_launcher_background${suffix(v)}.xml`), backgroundXml(v));
      writeFileSync(join(resDir, `mipmap-anydpi-v26/ic_launcher${suffix(v)}.xml`), adaptiveXml(v));
      writeFileSync(join(resDir, `mipmap-anydpi-v26/ic_launcher${suffix(v)}_round.xml`), adaptiveXml(v));
      for (const [folder, size] of densities) {
        await png(iconSvg(v, 512, 'rounded'), size, join(resDir, folder, `ic_launcher${suffix(v)}.png`));
        await png(iconSvg(v, 512, 'circle'), size, join(resDir, folder, `ic_launcher${suffix(v)}_round.png`));
      }
      console.log(`✓ Android ${v.id}`);
    }
  }

  for (const v of variants) {
    const dir = join(publicDir, 'app-icons', v.id);
    mkdirSync(dir, { recursive: true });
    writeFileSync(join(dir, 'icon.svg'), iconSvg(v, 512, 'rounded'));
    await png(iconSvg(v, 512, 'rounded'), 192, join(dir, 'icon-192.png'));
    await png(iconSvg(v, 512, 'rounded'), 512, join(dir, 'icon-512.png'));
    await png(iconSvg(v, 512, 'square'), 512, join(dir, 'icon-512-maskable.png'));
    await png(iconSvg(v, 512, 'square'), 180, join(dir, 'apple-touch-icon.png'));
    writeFileSync(join(dir, 'manifest.webmanifest'), manifestFor(v));
    console.log(`✓ web ${v.id}`);
  }

  // The default set at the root, referenced by vite.config.ts and index.html.
  const d = variants.find((v) => v.id === config.default);
  writeFileSync(join(publicDir, 'icon.svg'), iconSvg(d, 512, 'rounded'));
  await png(iconSvg(d, 512, 'rounded'), 192, join(publicDir, 'icon-192.png'));
  await png(iconSvg(d, 512, 'rounded'), 512, join(publicDir, 'icon-512.png'));
  await png(iconSvg(d, 512, 'square'), 192, join(publicDir, 'icon-192-maskable.png'));
  await png(iconSvg(d, 512, 'square'), 512, join(publicDir, 'icon-512-maskable.png'));
  await png(iconSvg(d, 512, 'square'), 180, join(publicDir, 'apple-touch-icon.png'));
  console.log(`✓ web default (${d.id})`);
}

generate().catch((err) => {
  console.error('Error generating icons:', err);
  process.exit(1);
});
